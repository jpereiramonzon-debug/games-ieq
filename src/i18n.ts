export const translate = (lang: Lang, key: string) => STRINGS[key]?.[INDEX[lang]] ?? key;

export function useT() {
  const lang = useStore((s) => s.lang);
  return useCallback((key: string) => STRINGS[key]?.[INDEX[lang]] ?? key, [lang]);
}
